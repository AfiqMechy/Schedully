  getDayName(dayKey, full = false) {
    const lang = this.translations[this.currentLang] || this.translations.en;
    if (full && lang.daysFull) {
      return lang.daysFull[dayKey] || dayKey;
    }
    return (lang.days && lang.days[dayKey]) || dayKey;
  },

  setLanguage(langCode) {
    if (!this.translations[langCode]) return;
    this.currentLang = langCode;
    try {
      localStorage.setItem('schedully_language', langCode);
    } catch (e) {}
    this.applyTranslations();
    if (window.schedullyApp && typeof window.schedullyApp._stagePending === 'function') {
      window.schedullyApp._stagePending(true);
    }
  },

  applyTranslations() {
    const lang = this.translations[this.currentLang] || this.translations.en;
    const ui = lang.ui || {};
    const enUi = (this.translations.en && this.translations.en.ui) || {};

    // 1. Update Language Modal active states & checkmarks
    document.querySelectorAll('.lang-option-pill').forEach(btn => {
      const code = btn.getAttribute('data-lang');
      const isSelected = (code === this.currentLang);
      btn.classList.toggle('active', isSelected);
      const checkIcon = btn.querySelector('.lang-check-icon');
      if (checkIcon) checkIcon.classList.toggle('hidden', !isSelected);
    });

    // 2. Update elements with data-i18n attributes
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = ui[key] || enUi[key];
      if (text !== undefined) {
        el.innerText = text;
      }
    });

    // 3. Update dock-icon-btn labels & badges
    document.querySelectorAll('.dock-icon-btn').forEach(btn => {
      const key = btn.getAttribute('data-dock-key');
      if (key && (ui[key] || enUi[key])) {
        const localizedLabel = ui[key] || enUi[key];
        btn.setAttribute('data-dock-label', localizedLabel);
        const span = btn.querySelector('.dock-icon-label');
        if (span) span.innerText = localizedLabel;
      }
    });

    // 4. Update current active dock section title badge
    const activeDockBtn = document.querySelector('.dock-icon-btn.dock-active');
    if (activeDockBtn) {
      const activeLabel = activeDockBtn.getAttribute('data-dock-label');
      const titleBadge = document.getElementById('theme-dock-section-title');
      if (titleBadge && activeLabel) {
        titleBadge.innerText = activeLabel;
      }
    }

    // 5. Update input placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const text = ui[key] || enUi[key];
      if (text !== undefined) {
        el.setAttribute('placeholder', text);
      }
    });

    // 6. Update tooltips / titles
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const text = ui[key] || enUi[key];
      if (text !== undefined) {
        el.setAttribute('title', text);
      }
    });

    // 7. Update lockscreen clock & date
    if (window.schedullyApp && typeof window.schedullyApp.updateClock === 'function') {
      window.schedullyApp.updateClock();
    }

    // 8. Update Quick Time Format Preview Badge
    const quickBadge = document.getElementById('quick-time-preview-badge');
    if (quickBadge && window.schedullyApp) {
      const mode = window.schedullyApp.cardTimeDisplayType || 'start';
      if (mode === 'both') quickBadge.innerText = ui.startAndEnd || enUi.startAndEnd || 'Start & End';
      else if (mode === 'end') quickBadge.innerText = ui.endOnly || enUi.endOnly || 'End Only';
      else quickBadge.innerText = ui.startOnly || enUi.startOnly || 'Start Only';
    }

    // 9. Re-render timetable grid, class list, and canvas ratio labels
    if (window.schedullyApp) {
      if (typeof window.schedullyApp.renderTimetableGrid === 'function') {
        window.schedullyApp.renderTimetableGrid();
      }
      if (typeof window.schedullyApp.renderClassList === 'function') {
        window.schedullyApp.renderClassList();
      }
      if (typeof window.schedullyApp.updateCanvasScreenRatio === 'function') {
        window.schedullyApp.updateCanvasScreenRatio();
      }
    }
  }
